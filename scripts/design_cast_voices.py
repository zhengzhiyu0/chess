def build():
    clips=[]
    for role in ROLES:
        rows=[row.strip() for row in SCRIPTS[role['id']].strip().splitlines() if row.strip()]
        assert len(rows)==30, (role['id'],len(rows))
        for category,row in zip(CATEGORIES,rows):
            texts=row.split('|')
            assert len(texts)==(5 if category=='player_brilliant' else 4), (role['id'],category)
            for number,text in enumerate(texts,1):
                clip_id=f"{role['id']}_{category}_{number:02}"
                actor='player' if category.startswith('player_') or category in ('opening_book_entry','opening_book_exit','tactic_zwischenzug','tactic_sacrifice','missed_mate','blunder_into_mate','queen_early','defense_found','comeback') else 'opponent'
