    for role in ROLES:
        out.extend([f"## {role['name']} · {role['style']}",'',f"音色：`{role['voice']}`（{role['voiceLabel']}）。{role['rationale']}",''])
        for category in CATEGORIES:
            out.extend([f'### {category}',''])
            out.extend(f"- `{c['id']}`：{c['text']}" for c in clips if c['role']==role['id'] and c['category']==category)
            out.append('')
    (ROOT/'docs/cast-voice-production.md').write_text('\n'.join(out).rstrip()+'\n',encoding='utf-8')
    print(json.dumps(dict(count=len(clips),roles=len(ROLES),categories=len(CATEGORIES)),ensure_ascii=False))


