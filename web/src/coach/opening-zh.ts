/**
 * 返回开局的基础中文名；没有可靠译名时返回 null（调用方回退英文原名）。
 * 先按冒号前的 family 精确匹配，再按逗号前的基础名回退，
 * 例如 `French Defense, Classical, 4. Bg5` → `French Defense`。
 */
export function openingZh(name: string): string | null {
  const family = name.split(':')[0].trim();
  const exact = ZH[family];
  if (exact) return exact;
  const base = family.split(',')[0].trim();
  return ZH[base] ?? null;
}
